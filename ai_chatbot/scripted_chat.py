def detect_topic(text):
    t = text.lower()
    for topic, words in KEYWORDS.items():
        if any(w in t for w in words):
            return topic
    return None

def choose_persona(text):
    topic = detect_topic(text)
    forced = {
        "tech": "zadr0t",
        "game": "zadr0t",
        "live": "mamkinBlogger",
        "fun": "tipoFUN",
        "portal": "FREEzzzy",
        "greet": random.choice(list(PERSONAS)),
    }
    if topic in forced:
        return forced[topic]
    return random.choice(list(PERSONAS))

class ScriptedChat:
    def __init__(self):
        self.used = defaultdict(lambda: deque(maxlen=80))
        self.last_persona = {}
        self.last_topic = {}

    def reply(self, chat_id, text):
        persona = choose_persona(text)
        topic = detect_topic(text)
        if topic is None:
            topic = random.choice(PERSONA_TOPIC[persona])
        bank = BANKS[persona].get(topic)
        if not bank:
            bank = BANKS[persona][random.choice(PERSONA_TOPIC[persona])]
        pool = [p + s for p in bank for s in COMMON_SUFFIXES]
        used = set(self.used[(chat_id, persona)])
        available = [p for p in pool if p not in used]
        if not available:
            available = pool
            self.used[(chat_id, persona)].clear()
        answer = random.choice(available)
        self.used[(chat_id, persona)].append(answer)
        self.last_persona[chat_id] = persona
        self.last_topic[chat_id] = topic
        return persona, answer

